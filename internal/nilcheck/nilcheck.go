// Package nilcheck validates injected interface dependencies at trust
// boundaries without being fooled by an interface containing a typed nil.
package nilcheck

import "reflect"

func IsNil(value any) bool {
	if value == nil {
		return true
	}
	reflected := reflect.ValueOf(value)
	switch reflected.Kind() {
	case reflect.Chan, reflect.Func, reflect.Interface, reflect.Map,
		reflect.Pointer, reflect.Slice:
		return reflected.IsNil()
	default:
		return false
	}
}
